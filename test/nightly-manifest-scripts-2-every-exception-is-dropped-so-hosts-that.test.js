// Upstream lists un-block some hosts with unconditional `@@` exceptions
// (EasyPrivacy `@@||content.ingbank.pl^`, AdGuard `@@||alllaw.112.2o7.net^`,
// `@@||puma.112.2o7.net^`, EasyPrivacy
// `@@||chart-embed.service.newrelic.com^$subdocument,xmlhttprequest`), while
// another list (or a parent-domain filter) blocks them. uBO applies those
// exceptions across all lists.
//
// Fixed in 0.3.5 (packer + runtime): an exception with no options at all
// (`@@||host^`) lifts the whole-domain block of that SAME host in every list,
// unless a list marks that block `$important`. Narrower or broader cases stay
// as they were (see the ignored test at the end).
import "../src/general/filter-options.js";
import "../src/threat/psl.js";
import "../src/general/never-block-captcha.js";
import updateSource from "../src/general/update.js" with { type: "text" };
import bundled from "../src/rules/general-network.json" with { type: "json" };
import { evaluate } from "./fixtures/dnr-matcher.js";

function assert(c, l) { if (!c) throw new Error(l); }
const U = {};
new Function(`${updateSource}\nreturn installGeneralAdblockUpdate;`)()(U);

const ADGUARD = "||content.ingbank.pl^\n||important.example.com^$important\n||keep.example.com^\n||typed.example.com^\n||content.ingbank.pl^$script,third-party";
const EASYPRIVACY = "@@||content.ingbank.pl^\n@@||important.example.com^\n@@||typed.example.com^$xmlhttprequest\n@@||parent.example.com^\n||parent.example.com^";

async function runPython(script) {
  const root = new URL("..", import.meta.url);
  const bins = Deno.build.os === "windows" ? [["py", "-3"], ["python"], ["python3"]] : [["python3"], ["python"]];
  for (const [bin, ...pre] of bins) {
    try {
      const out = await new Deno.Command(bin, { args: [...pre, "-c", script], cwd: root, env: { PYTHONDONTWRITEBYTECODE: "1" } }).output();
      if (out.code === 9009 || /Python was not found|Microsoft Store/.test(new TextDecoder().decode(out.stderr))) continue;
      assert(out.code === 0, new TextDecoder().decode(out.stderr));
      return new TextDecoder().decode(out.stdout);
    } catch (_err) { /* next binary */ }
  }
  throw new Error("no usable Python 3");
}

function check(label, whole, scoped) {
  assert(!whole.includes("content.ingbank.pl"), label + ": unconditional exception ignored: " + JSON.stringify(whole));
  assert(whole.includes("important.example.com"), label + ": an exception lifted a $important block");
  assert(whole.includes("keep.example.com"), label + ": control host missing");
  assert(whole.includes("typed.example.com"), label + ": a typed exception lifted a whole-domain block");
  assert(!whole.includes("parent.example.com"), label + ": same-list unconditional exception ignored");
  assert(scoped.some(([d]) => d === "content.ingbank.pl"), label + ": scoped entries of the host must stay (only whole-domain is lifted)");
}

Deno.test("packer: an unconditional @@||host^ lifts the same host's whole-domain block across lists", async () => {
  const script = [
    "import importlib.util, json",
    "from collections import OrderedDict",
    "from pathlib import Path",
    "spec = importlib.util.spec_from_file_location('pfl', Path('scripts/pack-filter-lists.py'))",
    "mod = importlib.util.module_from_spec(spec)",
    "spec.loader.exec_module(mod)",
    "texts = OrderedDict([('easyprivacy', " + JSON.stringify(EASYPRIVACY) + "), ('adguard_base', " + JSON.stringify(ADGUARD) + ")])",
    "buckets = OrderedDict(); scoped = OrderedDict(); lists = []",
    "for n, t in texts.items():",
    "    e = mod.extract_list(t); lists.append(e)",
    "    buckets[n], scoped[n] = e",
    "buckets, scoped = mod.apply_cross_list(buckets, scoped, lists)",
    "domains, _ = mod.merge_domains(buckets)",
    "sc, _ = mod.merge_scoped(scoped, domains)",
    "print(json.dumps({'domains': domains, 'scoped': sc}))",
  ].join("\n");
  const res = JSON.parse(await runPython(script));
  check("packer", res.domains, res.scoped);
});

Deno.test("runtime: the same exception rule in parseEntries + swap", () => {
  const payloads = { easyprivacy: U.parseEntriesFull(EASYPRIVACY), adguard_base: U.parseEntriesFull(ADGUARD) };
  const cross = U.crossListRules(payloads);
  const perList = {};
  const perScoped = {};
  for (const [n, p] of Object.entries(payloads)) {
    perList[n] = p.domains.filter((d) => cross.keepWhole(d));
    perScoped[n] = p.scoped.filter(([d, k]) => cross.keepScoped(d, k));
  }
  const domains = U.mergeDomains(perList);
  check("runtime", domains, U.mergeScoped(perScoped, domains));
});

